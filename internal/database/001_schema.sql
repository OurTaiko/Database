-- OurTaikoDatabase: official Taiko chart database.
-- Source design: OurTaikoLogs/taiko-official-schema.dbml (requirements R001–R013).
-- Table and column order follows the DBML. CHECK expressions, defaults and
-- indexes that the DBML only describes in notes are real constraints here.

CREATE SCHEMA IF NOT EXISTS auth;
CREATE SCHEMA IF NOT EXISTS internal;

CREATE TABLE internal.schema_migrations (
  version int4 PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.users (
  id text PRIMARY KEY,
  -- Bitflags: upload=0x1. The frontend shows the upload entry only when bit 0 is set.
  permission_flags int8 NOT NULL DEFAULT 0 CHECK (permission_flags >= 0),
  first_login_at timestamptz,
  last_active_at timestamptz,
  CHECK (first_login_at IS NULL OR (last_active_at IS NOT NULL AND last_active_at >= first_login_at))
);
CREATE INDEX users_recent_activity ON public.users (last_active_at DESC NULLS LAST, id);

CREATE TABLE auth.oidc_flows (
  state_hash text PRIMARY KEY,
  binding_hash text NOT NULL,
  nonce text NOT NULL,
  verifier text NOT NULL,
  return_path text NOT NULL,
  expires_at timestamptz NOT NULL
);

CREATE TABLE auth.sessions (
  token_hash text PRIMARY KEY,
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  csrf_token text NOT NULL,
  expires_at timestamptz NOT NULL,
  upstream_token bytea NOT NULL,
  -- Fanmade 036 (seven-day web sessions). The DBML baseline predates it; see R013.
  upstream_refresh_token bytea,
  upstream_expires_at timestamptz
);
CREATE INDEX sessions_user ON auth.sessions (user_id);

CREATE TABLE internal.pending_objects (
  storage_key text PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE internal.retired_files (
  storage_key text PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE internal.retired_score_requests (
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  idempotency_key text NOT NULL,
  PRIMARY KEY (user_id, idempotency_key)
);

-- Independent shared file records. Object key: {path_prefix}/{sha256}.{extension}.
-- Identical hash and extension reuse one record and one object (R005).
CREATE TABLE public.chart_resources (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage_key text NOT NULL UNIQUE,
  original_filename text NOT NULL,
  sha256 text NOT NULL CHECK (sha256 ~ '^[a-f0-9]{64}$'),
  byte_size int8 NOT NULL CHECK (byte_size > 0),
  extension text NOT NULL CHECK (extension ~ '^[a-z0-9]+$'),
  CHECK (storage_key = sha256 || '.' || extension)
);

-- The DBML keeps Fanmade's valid_chart_difficulties(difficulties, is_single)
-- CHECK but not its body. Official TJA files often hold single and double
-- (P1/P2) blocks together, so here is_single=false means "contains double
-- blocks" and still allows the plain single courses beside them.
CREATE FUNCTION public.valid_chart_difficulties(data jsonb, single boolean) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE d jsonb; keys text[] := ARRAY[]::text[]; course text; stars numeric; doubles int := 0;
BEGIN
  IF jsonb_typeof(data) <> 'array' THEN RETURN false; END IF;
  IF jsonb_array_length(data) > (CASE WHEN single THEN 5 ELSE 15 END) THEN RETURN false; END IF;
  FOR d IN SELECT value FROM jsonb_array_elements(data) LOOP
    IF jsonb_typeof(d) <> 'object' THEN RETURN false; END IF;
    IF NOT (d ?& ARRAY['course','level','maker']) OR (d - 'course' - 'level' - 'maker' - 'branching') <> '{}'::jsonb THEN RETURN false; END IF;
    IF jsonb_typeof(d->'course') <> 'string' OR jsonb_typeof(d->'maker') <> 'string' OR jsonb_typeof(d->'level') <> 'number' THEN RETURN false; END IF;
    IF d ? 'branching' AND jsonb_typeof(d->'branching') <> 'boolean' THEN RETURN false; END IF;
    course := d->>'course'; stars := (d->>'level')::numeric;
    IF course = ANY(keys) OR stars < 1 OR stars > 10 OR stars <> trunc(stars) OR octet_length(d->>'maker') > 500 THEN RETURN false; END IF;
    IF course ~ '^(Easy|Normal|Hard|Oni|Edit)_[12]p$' THEN
      IF single THEN RETURN false; END IF;
      doubles := doubles + 1;
    ELSIF course !~ '^(Easy|Normal|Hard|Oni|Edit)$' THEN
      RETURN false;
    END IF;
    keys := array_append(keys, course);
  END LOOP;
  RETURN single OR jsonb_array_length(data) = 0 OR doubles > 0;
END;
$$;

CREATE TABLE public.charts (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- 3000 is the user-reported current maximum, not an upper bound. Not unique (R009).
  nijiiro_id int4,
  official_id text,
  uploader_id text NOT NULL REFERENCES public.users(id) ON DELETE NO ACTION,
  tja_file int8 REFERENCES public.chart_resources(id) ON DELETE RESTRICT,
  audio_file int8 REFERENCES public.chart_resources(id) ON DELETE RESTRICT,
  cover_file int8 REFERENCES public.chart_resources(id) ON DELETE RESTRICT,
  preview_file int8 REFERENCES public.chart_resources(id) ON DELETE RESTRICT,
  description text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'published' CHECK (status IN ('published', 'deleted', 'hidden')),
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Latest change of the chart and its related data/resources (R010).
  update_at timestamptz NOT NULL DEFAULT now(),
  title text NOT NULL,
  subtitle text NOT NULL DEFAULT '',
  bpm float8 NOT NULL CHECK (bpm > 0 AND bpm < 'Infinity'::float8),
  offset_seconds float8 NOT NULL DEFAULT 0,
  demo_start float8 NOT NULL DEFAULT 0,
  duration float8 NOT NULL CHECK (duration > 0 AND duration <= 1200),
  title_translations jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(title_translations) = 'object'),
  subtitle_translations jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(subtitle_translations) = 'object'),
  is_single bool NOT NULL DEFAULT true,
  difficulties jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- Namco=0x01 Pop=0x02 Game=0x04 Anime=0x08 Vocaloid=0x10 Variety=0x20 Kids=0x40 Classics=0x80; 0=unclassified.
  category_flags int2 NOT NULL DEFAULT 0 CHECK (category_flags >= 0 AND category_flags <= 255),
  demo_end float8 NOT NULL,
  CHECK (status = 'deleted' OR (tja_file IS NOT NULL AND audio_file IS NOT NULL)),
  CHECK (public.valid_chart_difficulties(difficulties, is_single))
);
CREATE INDEX charts_tja_file ON public.charts (tja_file);
CREATE INDEX charts_audio_file ON public.charts (audio_file);
CREATE INDEX charts_cover_file ON public.charts (cover_file);
CREATE INDEX charts_preview_file ON public.charts (preview_file);
CREATE INDEX charts_published_recent ON public.charts (created_at DESC, id DESC) WHERE status = 'published';
CREATE INDEX charts_uploader ON public.charts (uploader_id, created_at DESC, id DESC);
CREATE INDEX charts_nijiiro_id ON public.charts (nijiiro_id) WHERE nijiiro_id IS NOT NULL;
CREATE INDEX charts_official_id ON public.charts (official_id) WHERE official_id IS NOT NULL;
CREATE INDEX charts_difficulties_gin ON public.charts USING gin (difficulties jsonb_path_ops);

-- R010: update_at follows every real change of the row; it never moves backwards.
CREATE FUNCTION public.charts_touch_update_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF to_jsonb(NEW) - 'update_at' IS DISTINCT FROM to_jsonb(OLD) - 'update_at' THEN
    NEW.update_at := greatest(OLD.update_at, clock_timestamp());
  ELSE
    -- Only update_at was written: a related row touching the chart.
    NEW.update_at := greatest(OLD.update_at, NEW.update_at);
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER charts_touch_update_at BEFORE UPDATE ON public.charts
  FOR EACH ROW EXECUTE FUNCTION public.charts_touch_update_at();

-- A changed shared file record refreshes every chart that references it.
CREATE FUNCTION public.chart_resources_touch_charts() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW IS DISTINCT FROM OLD THEN
    UPDATE public.charts SET update_at = greatest(update_at, clock_timestamp())
     WHERE NEW.id IN (tja_file, audio_file, cover_file, preview_file);
  END IF;
  RETURN NULL;
END;
$$;
CREATE TRIGGER chart_resources_touch_charts AFTER UPDATE ON public.chart_resources
  FOR EACH ROW EXECUTE FUNCTION public.chart_resources_touch_charts();

-- Related rows (votes, comments, statistics) also count as changes of the chart.
CREATE FUNCTION public.touch_related_chart() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE target int8;
BEGIN
  IF TG_OP = 'DELETE' THEN target := OLD.chart_id; ELSE target := NEW.chart_id; END IF;
  UPDATE public.charts SET update_at = greatest(update_at, clock_timestamp()) WHERE id = target;
  RETURN NULL;
END;
$$;

CREATE TABLE internal.upload_requests (
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE NO ACTION,
  idempotency_key text NOT NULL,
  payload_digest text NOT NULL,
  chart_id int8 REFERENCES public.charts(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  tja_sha256 text NOT NULL DEFAULT '',
  audio_sha256 text NOT NULL DEFAULT '',
  PRIMARY KEY (user_id, idempotency_key)
);
CREATE INDEX upload_requests_chart ON internal.upload_requests (chart_id);

CREATE TABLE public.chart_stats (
  chart_id int8 PRIMARY KEY REFERENCES public.charts(id) ON DELETE CASCADE,
  upvotes int4 NOT NULL DEFAULT 0 CHECK (upvotes >= 0),
  downvotes int4 NOT NULL DEFAULT 0 CHECK (downvotes >= 0),
  comment_count int4 NOT NULL DEFAULT 0 CHECK (comment_count >= 0)
);

CREATE TABLE public.chart_votes (
  chart_id int8 NOT NULL REFERENCES public.charts(id) ON DELETE CASCADE,
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE NO ACTION,
  value int2 NOT NULL CHECK (value IN (-1, 1)),
  voted_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (chart_id, user_id)
);
CREATE TRIGGER chart_votes_touch_chart AFTER INSERT OR UPDATE OR DELETE ON public.chart_votes
  FOR EACH ROW EXECUTE FUNCTION public.touch_related_chart();

CREATE TABLE public.comments (
  id text PRIMARY KEY,
  chart_id int8 NOT NULL REFERENCES public.charts(id) ON DELETE CASCADE,
  parent_id text REFERENCES public.comments(id) ON DELETE CASCADE,
  root_id text NOT NULL,
  depth int4 NOT NULL CHECK (depth >= 0 AND depth <= 1000),
  author_id text NOT NULL REFERENCES public.users(id) ON DELETE NO ACTION,
  body text NOT NULL CHECK (char_length(body) <= 10000),
  created_at timestamptz NOT NULL DEFAULT now(),
  edited_at timestamptz,
  deleted_at timestamptz,
  removed_at timestamptz,
  upvotes int4 NOT NULL DEFAULT 0 CHECK (upvotes >= 0),
  downvotes int4 NOT NULL DEFAULT 0 CHECK (downvotes >= 0),
  reply_count int4 NOT NULL DEFAULT 0 CHECK (reply_count >= 0),
  CHECK ((parent_id IS NULL) = (depth = 0) AND (parent_id IS NOT NULL OR root_id = id)),
  CHECK ((deleted_at IS NULL AND removed_at IS NULL) = (body <> ''))
);
CREATE INDEX comments_chart_roots ON public.comments (chart_id, created_at DESC) WHERE parent_id IS NULL;
CREATE INDEX comments_parent ON public.comments (parent_id);
CREATE INDEX comments_author ON public.comments (author_id, created_at DESC);
CREATE TRIGGER comments_touch_chart AFTER INSERT OR UPDATE OR DELETE ON public.comments
  FOR EACH ROW EXECUTE FUNCTION public.touch_related_chart();

CREATE TABLE public.comment_votes (
  comment_id text NOT NULL REFERENCES public.comments(id) ON DELETE CASCADE,
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE NO ACTION,
  value int2 NOT NULL CHECK (value IN (-1, 1)),
  voted_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (comment_id, user_id)
);

CREATE TABLE public.notification_mutes (
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE NO ACTION,
  kind text NOT NULL CHECK (kind ~ '^[a-z][a-z_]{0,39}$'),
  PRIMARY KEY (user_id, kind)
);

CREATE TABLE public.notifications (
  id text PRIMARY KEY,
  recipient_id text NOT NULL REFERENCES public.users(id) ON DELETE NO ACTION,
  kind text NOT NULL CHECK (kind ~ '^[a-z][a-z_]{0,39}$'),
  actor_id text REFERENCES public.users(id) ON DELETE NO ACTION,
  chart_id int8 REFERENCES public.charts(id) ON DELETE CASCADE,
  comment_id text REFERENCES public.comments(id) ON DELETE CASCADE,
  data jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(data) = 'object'),
  dedupe_key text,
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz,
  CHECK (actor_id IS NULL OR actor_id <> recipient_id)
);
CREATE UNIQUE INDEX notifications_dedupe ON public.notifications (recipient_id, dedupe_key) WHERE dedupe_key IS NOT NULL;
CREATE INDEX notifications_recipient ON public.notifications (recipient_id, created_at DESC);

CREATE TABLE public.scores (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES public.users(id) ON DELETE NO ACTION,
  song_id int8 NOT NULL REFERENCES public.charts(id) ON DELETE NO ACTION,
  difficulty text NOT NULL CHECK (difficulty ~ '^(Easy|Normal|Hard|Oni|Edit)(_[12]p)?$'),
  good int4 NOT NULL CHECK (good >= 0),
  ok int4 NOT NULL CHECK (ok >= 0),
  bad int4 NOT NULL CHECK (bad >= 0),
  score int8 NOT NULL CHECK (score >= 0 AND score <= 9007199254740991),
  drumroll int4 NOT NULL CHECK (drumroll >= 0),
  submitted_at timestamptz NOT NULL DEFAULT now(),
  idempotency_key text,
  payload_digest text NOT NULL CHECK (length(payload_digest) = 64),
  max_combo int4 NOT NULL CHECK (max_combo >= 0),
  replay_data jsonb CHECK (replay_data IS NULL OR jsonb_typeof(replay_data) = 'object'),
  clear_status int4 NOT NULL DEFAULT 0 CHECK (clear_status >= 0 AND clear_status <= 3),
  UNIQUE (user_id, idempotency_key)
);
CREATE INDEX scores_leaderboard_current ON public.scores (song_id, difficulty, score DESC, submitted_at);

