-- Requirements R015–R018: a chart's blocks are slots of course × side, as on
-- the arcade machine, where every course has a single, a 1P and a 2P chart
-- that may all differ. One row per block the stored TJA really contains; the
-- file itself stays whole. Replaces charts.difficulties and charts.is_single.
--
-- Which block a player reads is the client's rule, not a constraint here:
--   single play     single → p1
--   two players, 1P p1 → single
--   two players, 2P p2 → single → p1
CREATE TABLE public.chart_difficulties (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chart_id int8 NOT NULL REFERENCES public.charts(id) ON DELETE CASCADE,
  course text NOT NULL CHECK (course IN ('Easy', 'Normal', 'Hard', 'Oni', 'Edit')),
  -- The block's #START: plain = single, #START P1 = p1, #START P2 = p2.
  side text NOT NULL CHECK (side IN ('single', 'p1', 'p2')),
  level int2 NOT NULL CHECK (level >= 1 AND level <= 10),
  branching bool NOT NULL DEFAULT false,
  maker text NOT NULL DEFAULT '' CHECK (octet_length(maker) <= 500),
  UNIQUE (chart_id, course, side)
);
CREATE INDEX chart_difficulties_course_level ON public.chart_difficulties (course, level, chart_id);

INSERT INTO public.chart_difficulties (chart_id, course, side, level, branching, maker)
SELECT c.id,
       regexp_replace(d->>'course', '_[12]p$', ''),
       CASE WHEN d->>'course' ~ '_1p$' THEN 'p1' WHEN d->>'course' ~ '_2p$' THEN 'p2' ELSE 'single' END,
       (d->>'level')::int2,
       COALESCE((d->>'branching')::bool, false),
       d->>'maker'
  FROM public.charts c, jsonb_array_elements(c.difficulties) WITH ORDINALITY AS t(d, position)
 ORDER BY c.id, t.position;

-- Created after the backfill: moving existing data is not a change of the chart.
CREATE TRIGGER chart_difficulties_touch_chart AFTER INSERT OR UPDATE OR DELETE ON public.chart_difficulties
