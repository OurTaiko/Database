CREATE TEMP TABLE chart_id_map ON COMMIT DROP AS
SELECT id::text AS old_id, replace(gen_random_uuid()::text, '-', '') AS new_id,
       row_number() OVER (ORDER BY random()) AS number_id
  FROM public.charts;
CREATE UNIQUE INDEX ON chart_id_map (old_id);

