-- R035: user playlists, as on the Fanmade site. An ordered list of charts with
-- one category, whose genre the game uses to draw the playlist's folder, and
-- an optional cover stored like a chart cover together with a small JPEG of it
-- for the game, which cannot decode WebP. Other users may keep a public
-- playlist as a favorite. Covers are released by the program, which checks
-- that neither a chart nor a playlist still refers to the file.
CREATE TABLE public.playlists (
  id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id text NOT NULL REFERENCES public.users(id),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 50 AND name = btrim(name)),
  description text NOT NULL DEFAULT '' CHECK (char_length(description) <= 500),
  is_public bool NOT NULL DEFAULT false,
  -- Exactly one bit of charts.category_flags; Variety by default.
  category_flag int2 NOT NULL DEFAULT 32 CHECK (category_flag IN (1, 2, 4, 8, 16, 32, 64, 128)),
  cover_file int8 REFERENCES public.chart_resources(id),
  game_cover_file int8 REFERENCES public.chart_resources(id),
  CHECK ((cover_file IS NULL) = (game_cover_file IS NULL)),
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Also moves when charts are added, removed or reordered.
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX playlists_owner ON public.playlists (owner_id, updated_at DESC, id);
CREATE INDEX playlists_public ON public.playlists (updated_at DESC, id) WHERE is_public;
CREATE INDEX playlists_cover_file ON public.playlists (cover_file);
CREATE INDEX playlists_game_cover_file ON public.playlists (game_cover_file);

-- A deleted chart leaves every playlist. Positions order one playlist and need
-- not be contiguous; ties fall back to the time the chart was added.
CREATE TABLE public.playlist_items (
  playlist_id int8 NOT NULL REFERENCES public.playlists(id) ON DELETE CASCADE,
  chart_id int8 NOT NULL REFERENCES public.charts(id) ON DELETE CASCADE,
  position int4 NOT NULL CHECK (position >= 0),
  added_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (playlist_id, chart_id)
);
CREATE INDEX playlist_items_order ON public.playlist_items (playlist_id, position, added_at, chart_id);
CREATE INDEX playlist_items_chart ON public.playlist_items (chart_id);

-- A favorite of a playlist that turned private stays stored but is not shown.
CREATE TABLE public.playlist_favorites (
  playlist_id int8 NOT NULL REFERENCES public.playlists(id) ON DELETE CASCADE,
  user_id text NOT NULL REFERENCES public.users(id),
  favorited_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (playlist_id, user_id)
);
CREATE INDEX playlist_favorites_user ON public.playlist_favorites (user_id, favorited_at DESC);

